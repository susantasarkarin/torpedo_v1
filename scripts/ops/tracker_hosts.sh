#!/bin/bash
# First-party tracker hosts t.<site-domain> -> Torpedo /api/track (owner 2026-10-24).
# Idempotent; run hourly from cron. For each host:
#   DNS not pointing here yet -> HTTP block only (ACME challenge + tracker), nothing else
#   DNS points here, no cert   -> issue a Let's Encrypt cert (snap certbot, webroot)
#   cert present               -> HTTPS block, HTTP redirects to HTTPS
# Only /api/track/ is served on these hosts; everything else is 404.
set -u
HOSTS="t.business.surveyfieldwork.com t.cogentixresearch.com t.bimwavesolutions.com"
VM_IP="139.59.32.72"
CONF=/etc/nginx/sites-available/torpedo-tracker
WEBROOT=/var/www/certbot
CERTBOT=/snap/bin/certbot
LOG=/var/log/campaign_platform/tracker_hosts.log
mkdir -p "$WEBROOT" /var/log/campaign_platform

block_common() {
cat <<EOF
    location ^~ /.well-known/acme-challenge/ { root $WEBROOT; }
    location /api/track/ {
        proxy_pass http://127.0.0.1:8000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header CF-Connecting-IP "";      # not behind Cloudflare: never trust a client-sent value
        proxy_set_header X-Service-Token "";
        limit_req zone=torpedo_api burst=50 nodelay;
        proxy_read_timeout 30s;
    }
    location / { return 404; }
EOF
}

render() {
  {
    echo "# generated by /opt/crm-ops/tracker_hosts.sh -- do not edit by hand"
    for h in $HOSTS; do
      if [ -f "/etc/letsencrypt/live/$h/fullchain.pem" ]; then
        echo "server { listen 80; server_name $h;"
        echo "    location ^~ /.well-known/acme-challenge/ { root $WEBROOT; }"
        echo "    location / { return 301 https://\$host\$request_uri; } }"
        echo "server { listen 443 ssl http2; server_name $h;"
        echo "    ssl_certificate /etc/letsencrypt/live/$h/fullchain.pem;"
        echo "    ssl_certificate_key /etc/letsencrypt/live/$h/privkey.pem;"
        echo "    ssl_protocols TLSv1.2 TLSv1.3;"
        block_common
        echo "}"
      else
        echo "server { listen 80; server_name $h;"
        block_common
        echo "}"
      fi
    done
  } > "$CONF.new"
  if ! cmp -s "$CONF.new" "$CONF" 2>/dev/null; then
    mv "$CONF.new" "$CONF"
    ln -sf "$CONF" /etc/nginx/sites-enabled/torpedo-tracker
    if nginx -t 2>>"$LOG"; then systemctl reload nginx; echo "$(date -u +%FT%TZ) nginx reloaded" >> "$LOG"
    else echo "$(date -u +%FT%TZ) nginx -t FAILED, config kept for inspection" >> "$LOG"; rm -f /etc/nginx/sites-enabled/torpedo-tracker; fi
  else
    rm -f "$CONF.new"
  fi
}

render
changed=0
for h in $HOSTS; do
  [ -f "/etc/letsencrypt/live/$h/fullchain.pem" ] && continue
  ip=$(getent ahostsv4 "$h" | awk 'NR==1{print $1}')
  if [ "$ip" != "$VM_IP" ]; then
    echo "$(date -u +%FT%TZ) $h: DNS ${ip:-missing} (waiting for A record -> $VM_IP)" >> "$LOG"
    continue
  fi
  if $CERTBOT certonly --webroot -w "$WEBROOT" -d "$h" --non-interactive --agree-tos --keep-until-expiring \
       --register-unsafely-without-email >> "$LOG" 2>&1; then
    echo "$(date -u +%FT%TZ) $h: certificate issued" >> "$LOG"; changed=1
  else
    echo "$(date -u +%FT%TZ) $h: certbot failed (see above)" >> "$LOG"
  fi
done
[ "$changed" = 1 ] && render
exit 0
